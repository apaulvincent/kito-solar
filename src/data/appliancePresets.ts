export interface StarterProfile {
  id: 'small_home_wfh' | 'standard_family_home' | 'offgrid_cabin_farm';
  name: string;
  tagline: string;
  recommendedGoal: PrimaryGoal;
  recommendedGrid: GridReliability;
  items: Omit<ApplianceItem, 'id'>[];
}

const PRESETS_BY_ID = new Map(PRESET_APPLIANCES.map((preset) => [preset.id, preset]));

function fromPreset(
  presetId: string,
  overrides: {
    quantity: number;
    isCriticalBackup: boolean;
    hoursPerDay?: number;
    daytimeRatio?: number;
  }
): Omit<ApplianceItem, 'id'> {
  const preset = PRESETS_BY_ID.get(presetId);
  if (!preset) {
    throw new Error(`Unknown starter preset: ${presetId}`);
  }
  return {
    presetId: preset.id,
    name: preset.name,
    category: preset.category,
    loadType: preset.loadType,
    scheduleProfile: preset.scheduleProfile,
    quantity: overrides.quantity,
    runningWatts: preset.defaultRunningWatts,
    surgeMultiplier: preset.surgeMultiplier,
    dutyCycle: preset.dutyCycle,
    hoursPerDay: overrides.hoursPerDay ?? preset.defaultHoursPerDay,
    daytimeRatio: overrides.daytimeRatio ?? preset.defaultDaytimeRatio,
    isCriticalBackup: overrides.isCriticalBackup,
  };
}

